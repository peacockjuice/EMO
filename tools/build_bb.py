"""Build compact BB faces, preserving original bank offsets. Standard library only."""
from pathlib import Path
import runpy, json, hashlib
P=Path(__file__).resolve().parents[1]

def build():
    original=runpy.run_path(str(P/'emotion_sequences.py'))['SEQUENCES']
    size=(1+max(i for seq in original.values() for i,ms in seq))*1024
    base=(P/'emotions.bin').read_bytes()[:size]
    if len(base)!=size: raise ValueError('truncated source bank')
    extra=[]; sequences={}
    for key in ('rosto17','rosto03','rosto02','look','rosto04','rosto01'):
        indices={i for i,ms in original[key]}
        points=[(x,y) for i in indices for y in range(64) for x in range(128) if base[i*1024+x+y//8*128] & (1<<(y%8))]
        x0=min(x for x,y in points);x1=max(x for x,y in points)+1
        y0=min(y for x,y in points);y1=max(y for x,y in points)+1
        scale=min(1,104/(x1-x0),44/(y1-y0)); w=round((x1-x0)*scale);h=round((y1-y0)*scale)
        tx=(128-w)//2;ty=8+(48-h)//2;cache={}
        for i in indices:
            out=bytearray(1024)
            for y in range(h):
                sy=min(y1-1,y0+int(y/scale))
                for x in range(w):
                    sx=min(x1-1,x0+int(x/scale))
                    if base[i*1024+sx+sy//8*128] & (1<<(sy%8)):
                        px=x+tx;py=y+ty;out[px+py//8*128]|=1<<(py%8)
            data=bytes(out)
            if data not in extra:extra.append(data)
            cache[i]=size//1024+extra.index(data)
        sequences[key]=tuple((cache[i],ms) for i,ms in original[key])
    bank=base+b''.join(extra)
    (P/'emotions.bin').write_bytes(bank)
    manifest=P/'preview/full-manifest.json'
    if manifest.exists():
        value=json.loads(manifest.read_text());value.update(frames=len(bank)//1024,bytes=len(bank),sha256=hashlib.sha256(bank).hexdigest())
        manifest.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
    (P/'emo_bb_frames.py').write_text('# Generated by tools/build_bb.py; original offsets preserved.\nSEQUENCES = '+repr(sequences)+'\n')
    print('BB compact bank:',len(extra),'new frames;',size+len(extra)*1024,'bytes total')
    return sequences
if __name__=='__main__':build()
