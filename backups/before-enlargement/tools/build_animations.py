"""Build three animation samples from the approved 1-bit static PNGs."""
from pathlib import Path
import json, math, hashlib
from PIL import Image, ImageDraw
P = Path(__file__).resolve().parents[1]
OUT = P / "preview"

def base(n): return Image.open(OUT / ("Rosto-%02d.png" % n)).convert("1")
def pack(im):
    data = bytearray(1024)
    for y in range(64):
        for x in range(128):
            if im.getpixel((x,y)): data[x+y//8*128] |= 1 << (y%8)
    return bytes(data)

smile = base(1)
def blink(height):
    im = smile.copy()
    for x in (32, 87):
        box = (x,19,x+10,29)
        eye = smile.crop(box).resize((10,height), Image.Resampling.NEAREST)
        ImageDraw.Draw(im).rectangle((x,19,x+9,28),fill=0)
        im.paste(eye,(x,24-height//2))
    return im
happy = base(2)
def mouth(height):
    im = happy.copy(); box = (51,37,78,52)
    shape = happy.crop(box).resize((27,height),Image.Resampling.NEAREST)
    ImageDraw.Draw(im).rectangle((51,37,77,51),fill=0)
    im.paste(shape,(51,38))
    return im
cry = base(12)
def tears(amount):
    im = cry.copy()
    for left,right in ((21,44),(87,111)):
        for y in range(28,64):
            shift = round(amount*math.sin((y-27)/10))
            row = cry.crop((left,y,right,y+1))
            ImageDraw.Draw(im).line((left,y,right-1,y),fill=0)
            im.paste(row,(left+shift,y))
    return im
clips = {
    "sample_blink": [(smile,2400),(blink(4),80),(blink(1),100),(blink(4),80),(smile,700)],
    "sample_talk": [(happy,700),(mouth(9),180),(mouth(3),160),(mouth(9),180),(happy,240),(mouth(3),160),(happy,800)],
    "sample_cry": [(tears(k),180) for k in (0,1,2,1,0,-1,-2,-1)],
}
frames, timelines = [], {}
for name, seq in clips.items():
    timelines[name] = []
    for im, ms in seq:
        data = pack(im)
        if data not in frames: frames.append(data)
        timelines[name].append((frames.index(data), ms))
    assert pack(seq[0][0]) == pack({"sample_blink":smile,"sample_talk":happy,"sample_cry":cry}[name])
    seq[0][0].resize((512,256),Image.Resampling.NEAREST).save(OUT/(name+".gif"),save_all=True,append_images=[im.resize((512,256),Image.Resampling.NEAREST) for im,_ in seq[1:]],duration=[ms for _,ms in seq],loop=0,optimize=False,disposal=2)
    strip = Image.new("RGB",(len(seq)*256,150),"#20252b")
    draw = ImageDraw.Draw(strip)
    for i,(im,ms) in enumerate(seq):
        draw.text((i*256+4,4),str(ms)+" ms",fill="white")
        strip.paste(im.resize((256,128),Image.Resampling.NEAREST).convert("RGB"),(i*256,22))
    strip.save(OUT/(name+"-frames.png"))
data = b"".join(frames)
(P/"samples.bin").write_bytes(data)
(P/"sample_sequences.py").write_text("# Generated by tools/build_animations.py\nSEQUENCES = " + repr(timelines) + "\n")
(OUT/"animation-manifest.json").write_text(json.dumps({"sha256":hashlib.sha256(data).hexdigest(),"frames":len(frames),"bytes":len(data),"sequences":timelines},indent=2))
print("Built",len(frames),"unique frames;",len(data),"bytes; static starting poses verified")
