def glyph(ch):
    n=ord(ch)
    return n-32 if 32<=n<=90 else 59+n-1040 if 1040<=n<=1071 else 91 if n==1025 else 31

def text(o,value,x,y,scale=1):
    for ch in value:
        if x>=128:break
        if x>-6*scale:
            start=glyph(ch)*5
            for col in range(5):
                px=x+col*scale
                if px<128 and px+scale>0:
                    bits=DATA[start+col]
                    for row in range(7):
                        if bits&(1<<row):
                            if scale==1:o.pixel(px,y+row,1)
                            else:o.fill_rect(max(0,px),y+row*scale,min(128,px+scale)-max(0,px),scale,1)
        x+=6*scale
